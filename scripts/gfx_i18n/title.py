"""Title menu words NOVO JOGO / CONTINUAR (DATA_D2 scene 0, blob at S:0x2D8AC, objects 16/17, frames 0 and 1).
Pixel redraw in the lettering of NEW GAME / CONTINUE: letters are cut from the original words (white fill 13 + black edge 14), V J R are drawn
here in the same stroke vocabulary, the 2-px diagonal drop shadow (colours 3..6) is regenerated by the rule measured on the originals."""
import sys, random, os
sys.path.insert(0, os.path.dirname(__file__))
from lib import *; from data import *

D = Data('DATA_D2')
BLOB_ADDR = 186540
ANIM = 239348
FILL, EDGE, DIM_FILL, DIM_EDGE = 13, 14, 12, 15

def strips(blob):
    vram = bytearray(0x10000); vram[0x20:0x20 + len(blob)] = blob
    return tiles_from_bytes(bytes(vram))

# (name, piece list as (x, first tile), width in tiles of the last piece): tiles are numbered column-major, 2 rows per column
WORDS = {
    'new_b': [(16, 0x06), (48, 0x0E), (80, 0x16)],   # NEW GAME bright
    'cont_b': [(16, 0x1E), (48, 0x26), (80, 0x2E)],  # CONTINUE bright (last piece 3 columns in the original)
    'new_d': [(16, 0x44), (48, 0x4C), (80, 0x54)],   # dim copies (fill 12, edge 15)
    'cont_d': [(16, 0x5C), (64 - 16, 0x64), (80, 0x6C)],
}
COLS = {'new_b': (4, 4, 4), 'cont_b': (4, 4, 3), 'new_d': (4, 4, 4), 'cont_d': (4, 4, 3)}

def read_strip(tiles, key):
    cols = COLS[key]; w = 16 + 8 * sum(cols)
    g = np.zeros((16, 112), dtype=np.uint8)
    for (x, t0), nc in zip(WORDS[key], cols):
        for c in range(nc):
            for r in range(2):
                g[r * 8:(r + 1) * 8, x + c * 8:x + c * 8 + 8] = tiles[t0 + c * 2 + r]
    return g

def write_strip(tiles, key, g, ncols=(4, 4, 4)):
    for (x, t0), nc in zip(WORDS[key], ncols):
        for c in range(nc):
            for r in range(2):
                tiles[t0 + c * 2 + r] = g[r * 8:(r + 1) * 8, x + c * 8:x + c * 8 + 8]

def mask(g, fill=FILL, edge=EDGE):
    """letter layer: 1 where white fill, 2 where black edge"""
    m = np.zeros(g.shape, dtype=np.uint8)
    m[g == fill] = 1; m[g == edge] = 2
    return m

def cut(m, x0, x1):
    return m[:, x0:x1 + 1].copy()

def art(rows, top=4):
    """ASCII art (# fill, + edge) of rows starting at strip row `top` -> layer array 16 x w"""
    w = max(len(r) for r in rows)
    m = np.zeros((16, w), dtype=np.uint8)
    for i, r in enumerate(rows):
        for j, ch in enumerate(r):
            if ch == '#': m[top + i, j] = 1
            elif ch == '+': m[top + i, j] = 2
    return m

V = art([
    '.####+..####+',
    '..##++...#+++',
    '..##+....##+.',
    '...##+...#++.',
    '...##+..##+..',
    '....##+.#++..',
    '....###.#+...',
    '.....###++...',
    '......##+....',
    '......++.....',
])
J = art([
    '..########',
    '....##++++',
    '....##+...',
    '....##+...',
    '....##+...',
    '....##+...',
    '##..##+...',
    '###.##+...',
    '.#####+...',
    '..++++....',
])
R = art([
    '.########.',
    '..##++++#+',
    '..##+...#+',
    '..##+...#+',
    '..#######+',
    '..##+##+..',
    '..##+.##+.',
    '..##+..##+',
    '.####..###',
    '..++++..++',
])

def compose(parts, x0, width=112):
    """parts: list of (layer, gap_before). Letter pixels (fill / edge) on a 16 x width layer; the fill of a later letter wins."""
    out = np.zeros((16, width), dtype=np.uint8)
    x = x0
    for layer, gap in parts:
        x += gap
        w = layer.shape[1]
        sub = out[:, x:x + w]
        sub[layer > 0] = layer[layer > 0] if True else 0
        x += w
    return out

def shade(layer, seed=7, fill=FILL, edge=EDGE):
    """strip of colour indices: letters + drop shadow = the letter shape shifted by (+2, +2), colours 3..6 (measured on the original words)"""
    h, w = layer.shape
    g = np.zeros((h, w), dtype=np.uint8)
    rnd = random.Random(seed)
    sh = np.zeros((h, w), dtype=bool)
    ys, xs = np.nonzero(layer)
    for y, x in zip(ys, xs):
        if y + 2 < h and x + 2 < w: sh[y + 2, x + 2] = True
    for y in range(h):
        for x in range(w):
            if layer[y, x] == 1: g[y, x] = fill
            elif layer[y, x] == 2: g[y, x] = edge
            elif sh[y, x]:
                g[y, x] = rnd.choices([3, 4, 5, 6], [0.42, 0.37, 0.17, 0.04])[0]
    return g

def letters_from(tiles):
    nb = mask(read_strip(tiles, 'new_b')); cb = mask(read_strip(tiles, 'cont_b'))
    L = {}
    L['N'] = cut(nb, 18, 28); L['G'] = cut(nb, 60, 68); L['A'] = cut(nb, 70, 80)
    L['C'] = cut(cb, 18, 26); L['O'] = cut(cb, 28, 36); L['T'] = cut(cb, 50, 58); L['I'] = cut(cb, 60, 64); L['U'] = cut(cb, 78, 87)
    L['V'] = V; L['J'] = J; L['R'] = R
    return L, nb, cb

def word(L, text, x0=17, space=5, tight=1):
    parts = []
    for ch in text:
        if ch == ' ': parts.append((np.zeros((16, 0), dtype=np.uint8), space - tight)); continue
        parts.append((L[ch], tight))
    return compose(parts, x0 - tight)

def build(tiles, seed=7):
    """returns the new tile array and the four new strips (colour index images)"""
    L, nb, cb = letters_from(tiles)
    t2 = tiles.copy()
    nov = shade(word(L, 'NOVO JOGO'), seed)
    con = shade(word(L, 'CONTINUAR'), seed + 1)
    dimmap = {FILL: DIM_FILL, EDGE: DIM_EDGE}
    def dim(g): 
        o = g.copy()
        for a, b in dimmap.items(): o[g == a] = b
        return o
    out = {'new_b': nov, 'cont_b': con, 'new_d': dim(nov), 'cont_d': dim(con)}
    for k, g in out.items(): write_strip(t2, k, g, (4, 4, 4))
    return t2, out

