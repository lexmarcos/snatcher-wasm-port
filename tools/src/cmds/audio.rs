//! audio subcommands. Return None if the command is not handled here.
//!
//!   snt audio-pcm <files-dir> <out-dir>     voices, PCM sfx banks, drum kit → WAV + pcm.json
use sncore::audio::*;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

pub fn dispatch(args: &[String]) -> Option<Result<(), String>> {
    match args[0].as_str() {
        "audio-pcm" if args.len() == 3 => Some(audio_pcm(Path::new(&args[1]), Path::new(&args[2]))),
        _ => None,
    }
}

fn w(p: &Path, d: &[u8]) -> Result<(), String> {
    if let Some(dir) = p.parent() { fs::create_dir_all(dir).map_err(|e| e.to_string())?; }
    fs::write(p, d).map_err(|e| format!("{}: {e}", p.display()))
}

fn audio_pcm(files: &Path, out: &Path) -> Result<(), String> {
    let rd = |n: &str| fs::read(files.join(n)).map_err(|e| format!("{n}: {e}"));
    let lt = rd("PCMLT_01.BIN")?;
    let ld = rd("PCMLD_01.BIN")?;
    let dr = rd("PCMDRMDT.BIN")?;
    let voices = parse_voice_table(&lt);
    let sfx = parse_sfx_table(&lt);
    let vrate = fd_to_hz(VOICE_FD).round() as u32;
    let mut j = String::from("{\n  \"note\": \"generated by snt audio-pcm; see docs/re/audio.md\",\n");
    let _ = write!(j, "  \"pcm_clock_hz\": {:.3},\n  \"voice_rate_hz\": {vrate},\n  \"voices\": {{\n", PCM_CLOCK_HZ);
    let mut first = true;
    let mut banks: Vec<(u16, Vec<Segment>)> = Vec::new();
    for v in &voices {
        let blk = &ld[v.sector as usize * 2048..(v.sector as usize + v.sectors as usize) * 2048];
        if v.kind == 1 {
            banks.push((v.id, parse_segments(blk)));
            continue;
        }
        let s = decode_sm8(blk);
        let name = format!("voice/v{:04}.wav", v.id);
        w(&out.join(&name), &wav_bytes(&s, vrate, 1))?;
        if !first { j.push_str(",\n"); }
        first = false;
        let _ = write!(j, "    \"{}\": {{\"file\": \"{}\", \"samples\": {}, \"seconds\": {:.3}, \"kind\": {}, \"env\": {}, \"pan\": {}, \"prio\": {}}}",
            v.id, name, s.len(), s.len() as f64 / vrate as f64, v.kind, v.env, v.pan, v.prio);
    }
    j.push_str("\n  },\n  \"banks\": {\n");
    for (bi, (id, segs)) in banks.iter().enumerate() {
        let _ = write!(j, "    \"{id}\": {{");
        for (si, g) in segs.iter().enumerate() {
            let name = format!("bank/b{:02}_{:05x}.wav", id, g.offset);
            w(&out.join(&name), &wav_bytes(&g.samples, g.rate as u32, 1))?;
            let _ = write!(j, "{}\"{:#x}\": {{\"file\": \"{}\", \"rate\": {}, \"samples\": {}}}", if si > 0 { ", " } else { "" }, g.offset, name, g.rate, g.samples.len());
        }
        let _ = write!(j, "}}{}\n", if bi + 1 < banks.len() { "," } else { "" });
    }
    j.push_str("  },\n  \"drum\": {");
    let dsegs = parse_segments(&dr);
    for (si, g) in dsegs.iter().enumerate() {
        let name = format!("drum/d{:05x}.wav", g.offset);
        w(&out.join(&name), &wav_bytes(&g.samples, g.rate as u32, 1))?;
        let _ = write!(j, "{}\n    \"{:#x}\": {{\"file\": \"{}\", \"rate\": {}, \"samples\": {}}}", if si > 0 { "," } else { "" }, g.offset, name, g.rate, g.samples.len());
    }
    j.push_str("\n  },\n  \"sfx\": {");
    for (k, e) in sfx.iter().enumerate() {
        let (src, off) = if e.addr >= BANK_BASE { ("bank", e.addr - BANK_BASE) } else { ("drum", e.addr - DRUM_BASE) };
        let _ = write!(j, "{}\n    \"{}\": {{\"src\": \"{}\", \"offset\": \"{:#x}\", \"fd\": {}, \"rate_hz\": {:.1}, \"env\": {}, \"pan\": {}, \"prio\": {}, \"chan\": {}}}",
            if k > 0 { "," } else { "" }, e.id, src, off, e.fd, fd_to_hz(e.fd), e.env, e.pan, e.prio, e.chan);
    }
    j.push_str("\n  }\n}\n");
    w(&out.join("pcm.json"), j.as_bytes())?;
    println!("voices {} banks {} drum segs {} sfx {}", voices.len() - banks.len(), banks.len(), dsegs.len(), sfx.len());
    Ok(())
}
